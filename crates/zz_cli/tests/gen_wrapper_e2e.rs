//! Wrapper-generation E2E (#235): `zz generate-wrapper` emits
//! `src/<pkg>.zz` from `plugin.zzi`; `--check` fails on drift;
//! hand-written files are never overwritten; the generated wrappers
//! call through on both engines. Tempdir pattern mirrors
//! `plugin_bytes_e2e.rs`.

use std::path::{Path, PathBuf};
use std::process::Command;

/// The compiled `zz` binary (target/debug/zz).
fn zz_bin() -> PathBuf {
    let exe = std::env::current_exe().unwrap();
    let deps = exe.parent().unwrap();
    deps.parent().unwrap().join("zz")
}

fn run_zz(dir: &Path, args: &[&str]) -> (i32, String, String) {
    let out = Command::new(zz_bin())
        .args(args)
        .current_dir(dir)
        .output()
        .expect("zz binary should run");
    (
        out.status.code().unwrap_or(-1),
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

fn write(dir: &Path, rel: &str, content: &str) {
    let p = dir.join(rel);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(&p, content).unwrap();
}

// ---------------------------------------------------------------------------
// Toy package with two externs (bytes + ints) to prove multi-wrapper output
// ---------------------------------------------------------------------------

const PKG_TOML: &str = r#"[package]
name = "wsum"
version = "0.1.0"

[native]
backend = "cc"
manifest = "plugin.zzi"

[native.build-cc]
sources = ["csrc/wsum.c"]
"#;

const PKG_ZZI: &str = r#"// Version: 1
// C-ABI: 1
// Plugin-version: 0.1.0

extern "C" {
    func wsum.sum(buf: bytes) -> int
    func wsum.add(a: int, b: int) -> int
}
"#;

const PKG_C: &str = r#"#include <stddef.h>
#include <stdint.h>

const unsigned int ZZ_C_PLUGIN_ABI_VERSION = 1;

long long wsum_sum(const uint8_t *ptr, size_t len) {
    long long total = 0;
    for (size_t i = 0; i < len; i++) {
        total += ptr[i];
    }
    return total;
}

long long wsum_add(long long a, long long b) {
    return a + b;
}
"#;

const CONSUMER_TOML: &str = r#"[package]
name = "wsumuse"
version = "0.1.0"

[dependencies.wsum]
path = "../wsum"
"#;

const CONSUMER_MAIN: &str = r#"import wsum
import std.bytes

func main() -> Result<int, str> {
    b := bytes.finish([1, 0, 2, 250])?
    println("sum={wsum.sum(b)}")
    println("add={wsum.add(40, 2)}")
    println("wsum-ok")
    return .ok(0)
}
"#;

/// Layout: <tmp>/wsum (package) + <tmp>/use (consumer with path dep).
fn scaffold(dir: &Path) {
    let pkg = dir.join("wsum");
    write(&pkg, "zz.toml", PKG_TOML);
    write(&pkg, "plugin.zzi", PKG_ZZI);
    write(&pkg, "csrc/wsum.c", PKG_C);

    let consumer = dir.join("use");
    write(&consumer, "zz.toml", CONSUMER_TOML);
    write(&consumer, "src/main.zz", CONSUMER_MAIN);
}

#[test]
fn generate_wrapper_round_trip_and_call_through() {
    let dir = std::env::temp_dir().join(format!("zz-genwrap-e2e-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    scaffold(&dir);
    let pkg = dir.join("wsum");
    let consumer = dir.join("use");

    // Generate: marker + one wrapper per extern, sorted, calling the
    // C-symbol alias (the only spelling that resolves in-module).
    let (code, stdout, stderr) = run_zz(&pkg, &["generate-wrapper"]);
    let combined = format!("{stdout}\n{stderr}");
    assert_eq!(code, 0, "generate failed: {combined}");
    let gen_path = pkg.join("src/wsum.zz");
    let gen = std::fs::read_to_string(&gen_path).expect("wrapper written");
    assert!(
        gen.starts_with("// GENERATED by `zz generate-wrapper`"),
        "marker missing:\n{gen}"
    );
    assert!(
        gen.contains("pub func sum(buf: bytes) -> int")
            && gen.contains("pub func add(a: int, b: int) -> int"),
        "both wrappers present, sorted:\n{gen}"
    );
    assert!(
        gen.contains("wsum_sum(buf)") && gen.contains("wsum_add(a, b)"),
        "alias call-through missing:\n{gen}"
    );

    // --check passes on fresh output; regenerate is byte-identical.
    let (code, _, stderr) = run_zz(&pkg, &["generate-wrapper", "--check"]);
    assert_eq!(code, 0, "check failed on fresh output: {stderr}");
    let (code, _, stderr) = run_zz(&pkg, &["generate-wrapper"]);
    assert_eq!(code, 0, "regenerate failed: {stderr}");
    let gen2 = std::fs::read_to_string(&gen_path).expect("wrapper rewritten");
    assert_eq!(gen, gen2, "regeneration is not byte-identical");

    // Drift: a new extern fails --check until regenerated.
    let zzi_path = pkg.join("plugin.zzi");
    let zzi = std::fs::read_to_string(&zzi_path).unwrap();
    std::fs::write(
        &zzi_path,
        zzi.replace(
            "    func wsum.add(a: int, b: int) -> int",
            "    func wsum.add(a: int, b: int) -> int\n    func wsum.neg(n: int) -> int",
        ),
    )
    .unwrap();
    let (code, _, stderr) = run_zz(&pkg, &["generate-wrapper", "--check"]);
    assert_ne!(code, 0, "--check passed despite drift");
    assert!(stderr.contains("stale"), "drift error missing: {stderr}");
    // Restore the zzi (the C file never had `neg`; the drift was synthetic).
    std::fs::write(&zzi_path, zzi).unwrap();
    let (code, _, stderr) = run_zz(&pkg, &["generate-wrapper", "--check"]);
    assert_eq!(code, 0, "check failed after restore: {stderr}");

    // Hand-written files are never overwritten.
    std::fs::write(&gen_path, "// hand-written\n").unwrap();
    let (code, _, stderr) = run_zz(&pkg, &["generate-wrapper"]);
    assert_ne!(code, 0, "overwrote a hand-written file");
    assert!(stderr.contains("hand-written"), "refusal missing: {stderr}");
    std::fs::remove_file(&gen_path).unwrap();
    let (code, _, stderr) = run_zz(&pkg, &["generate-wrapper"]);
    assert_eq!(code, 0, "regenerate after refusal failed: {stderr}");

    // The generated wrappers call through on both engines.
    let (code, _, stderr) = run_zz(&consumer, &["install"]);
    assert_eq!(code, 0, "install failed: {stderr}");
    let (code, stdout, stderr) = run_zz(&consumer, &["run", "src/main.zz"]);
    assert_eq!(code, 0, "run failed: {stderr}");
    assert!(
        stdout.contains("sum=253") && stdout.contains("add=42") && stdout.contains("wsum-ok"),
        "unexpected VM output: {stdout}"
    );
    let (code, _, stderr) = run_zz(&consumer, &["build", "src/main.zz"]);
    assert_eq!(code, 0, "build failed: {stderr}");
    let bin = consumer.join("bin/wsumuse");
    assert!(bin.is_file(), "project binary missing");
    let out = Command::new(&bin).output().expect("binary should run");
    let bin_stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        bin_stdout.contains("sum=253")
            && bin_stdout.contains("add=42")
            && bin_stdout.contains("wsum-ok"),
        "unexpected AOT output: {bin_stdout}"
    );

    let _ = std::fs::remove_dir_all(&dir);
}
